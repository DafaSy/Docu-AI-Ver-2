const fs = require('fs');
const path = require('path');

const directoryPath = path.join(__dirname, '..', 'src');

function walk(dir) {
    let results = [];
    const list = fs.readdirSync(dir);
    list.forEach(file => {
        file = path.join(dir, file);
        const stat = fs.statSync(file);
        if (stat && stat.isDirectory()) { 
            results = results.concat(walk(file));
        } else {
            if (file.endsWith('.tsx') || file.endsWith('.ts')) {
                results.push(file);
            }
        }
    });
    return results;
}

const files = walk(directoryPath);

// The regex looks for prefixes like hover:, focus:, group-hover:, sm:, etc.
// followed by the light mode class, then whitespace, then dark: followed by the dark mode class.
// We only want to target the specific combinations generated by the previous script.
// But we can generalize:
// Match: (sm|md|lg|xl|2xl|hover|focus|active|group-hover|focus-within|focus-visible):([a-z0-9\-\[\]\.\/]+)\s+dark:([a-z0-9\-\[\]\.\/]+)
// We need to be careful not to match things that ALREADY have the prefix in the dark mode class, 
// e.g. "hover:bg-white dark:hover:bg-black". The dark class is "hover:bg-black", which starts with "hover:".
// So we ensure the dark class does NOT start with the matched prefix.

const regex = /\b([a-z\-]+):([a-z0-9\-\[\]\.\/]+)\s+dark:(?!([a-z\-]+):)([a-z0-9\-\[\]\.\/]+)\b/g;

let filesModified = 0;

files.forEach(file => {
    let content = fs.readFileSync(file, 'utf8');
    let original = content;
    
    // We only want to apply this if the light class matches one of the replacements from before.
    // Actually, any prefix missing from dark mode is a bug!
    content = content.replace(regex, (match, prefix, lightClass, darkClassPrefix, darkClass) => {
        // e.g. match = "hover:bg-ink-50 dark:bg-[#070b12]"
        // prefix = "hover"
        // lightClass = "bg-ink-50"
        // darkClass = "bg-[#070b12]"
        return `${prefix}:${lightClass} dark:${prefix}:${darkClass}`;
    });
    
    if (content !== original) {
        fs.writeFileSync(file, content);
        filesModified++;
        console.log(`Updated: ${file}`);
    }
});

console.log(`Complete. Modified ${filesModified} files.`);
